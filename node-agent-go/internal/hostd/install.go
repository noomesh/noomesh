// Self-installation.
//
// This is not convenience polish; it is the difference between a component
// people run and one they don't. Installing the bash watcher meant: copy a
// unit file, know whether your box wants --user or system-wide, know that
// WSL2 needs systemd enabled in /etc/wsl.conf and a `wsl --shutdown`, know the
// nohup/tmux fallback if it doesn't, and install bash+jq+inotifywait. Every
// one of those is a step an operator can skip, and skipping any of them
// produces the same silent symptom: the gateway queues repairs nothing runs.
//
// `noo-hostd install` is one command that writes the unit for whichever
// supervisor is actually present, and tells you plainly when there isn't one.

type InstallOptions struct {
	// Root is the project root the daemon will operate in.
	Root string
	// System installs to /etc/systemd/system instead of the user manager.
	// Default is the USER manager: it needs no sudo and it inherits the
	// operator's docker group membership and their age key at
	// ~/.config/sops/age/keys.txt, which a system unit running as root would
	// not find.
	System bool
	// BinPath is the installed binary location. Empty means "the running
	// executable", resolved to an absolute path.
	BinPath string
	// DryRun prints the unit instead of writing it.
	DryRun bool
	// Mode selects the unit shape: ModeWorker installs the
	// worker daemon (system unit, root, worker spool, no project root).
	// Empty/ModeController is the earlier controller shape.
	Mode string
}

const systemdUnitTmpl = `# noo-hostd.service — host-side executor for the gateway command spool.
#
# The gateway container has ZERO Docker access. It drops atomic JSON command
# files into {{.Root}}/.noo-host-spool (bind-mounted to /var/run/noo-spool
# inside the container); this service watches that directory on the HOST and
# performs the docker/compose operations.
#
# Generated by "noo-hostd install". Re-run that command after upgrading the
# binary; do not hand-edit — a hand-edited unit is how the fleet ends up with
# eight subtly different ones.

[Unit]
Description=PAI Host Daemon (gateway command spool executor)
Documentation=https://github.com/noomesh/noomesh
# After= only, never Requires=. Docker frequently runs as a SysV service
# rather than a systemd unit (WSL2 does), and a hard Requires= on a unit that
# does not exist fails the start outright with "Unit docker.service not found".
# After= is ignored when the unit is absent, and the daemon tolerates docker
# being briefly unavailable anyway.
After=docker.service network-online.target

[Service]
Type=simple
WorkingDirectory={{.Root}}
ExecStart={{.Bin}} run --root {{.Root}}
Restart=always
RestartSec=3
{{if .System}}User={{.User}}
{{end}}# systemd's default PATH omits ~/.local/bin, where the noo CLI installs.
# db-resync shells out to it; without this the op fails with exit 127 and no
# explanation. The daemon also resolves the CLI by absolute path as a backstop.
Environment=PATH={{.Home}}/.local/bin:/usr/local/bin:/usr/bin:/bin
StandardOutput=journal
StandardError=journal
SyslogIdentifier=noo-hostd

[Install]
WantedBy={{if .System}}multi-user.target{{else}}default.target{{end}}
`

const workerUnitTmpl = `# noo-hostd.service — worker-mode host executor.
#
# The ONLY root process a worker runs for cluster reasons. No network
# listener — the node-agent (unprivileged, mTLS on :8081) stages work by
# writing spool files into {{.Spool}}; this daemon performs the fixed ops
# that genuinely need root (restart-agent, fetch-bundle, the harness
# lifecycle, disk-reclaim, journal reads) and nothing else. It installs no
# binaries: swap-agent is retired and refused — agent
# binaries arrive only in a signed bundle over the pull rail.
#
# Generated by "noo-hostd install --mode worker". Re-run after upgrading
# the binary; do not hand-edit.

[Unit]
Description=PAI Worker Host Daemon (agent restart / fetch executor)
Documentation=https://github.com/noomesh/noomesh

[Service]
Type=simple
ExecStart={{.Bin}} run --mode worker
Restart=always
RestartSec=3
User=root
Environment=PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
StandardOutput=journal
StandardError=journal
SyslogIdentifier=noo-hostd

[Install]
WantedBy=multi-user.target
`

const launchdPlistTmpl = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by ` + "`noo-hostd install`" + `. See noo-hostd.service for the systemd equivalent. -->
<plist version="1.0">
<dict>
  <key>Label</key><string>net.personifai.noo-hostd</string>
  <key>ProgramArguments</key>
  <array>
    <string>{{.Bin}}</string><string>run</string>
    <string>--root</string><string>{{.Root}}</string>
  </array>
  <key>WorkingDirectory</key><string>{{.Root}}</string>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key><string>{{.Home}}/.local/bin:/usr/local/bin:/usr/bin:/bin</string>
  </dict>
  <key>StandardOutPath</key><string>{{.Root}}/.noo-host-spool/hostd.log</string>
  <key>StandardErrorPath</key><string>{{.Root}}/.noo-host-spool/hostd.log</string>
</dict>
</plist>
`

type unitVars struct {
	Root, Bin, User, Home, Spool string
	System                       bool
}

// Install writes and activates the service definition for whichever supervisor
// this host actually has.
func Install(opts InstallOptions) error {
	bin := opts.BinPath
	if bin == "" {
		self, err := os.Executable()
		if err != nil {
			return fmt.Errorf("cannot resolve own path: %w", err)
		}
		bin, _ = filepath.Abs(self)
	}
	root, err := filepath.Abs(opts.Root)
	if err != nil {
		return err
	}
	home, _ := os.UserHomeDir()
	vars := unitVars{Root: root, Bin: bin, Home: home, Spool: WorkerSpoolDir, System: opts.System, User: os.Getenv("USER")}

	if opts.Mode == ModeWorker {
		// Workers are systemd-only by design
		// Windows means WSL2. The worker daemon is root by design — it IS
		// the confined root — so this is always a system unit.
		opts.System = true
		vars.System = true
		if !opts.DryRun {
			if err := os.MkdirAll(WorkerSpoolDir, 0o755); err != nil {
				return fmt.Errorf("cannot create worker spool %s (needs root): %w", WorkerSpoolDir, err)
			}
		}
		// A Darwin worker gets a system LaunchDaemon, not the per-user
		// LaunchAgent the controller mode uses. Worker mode exists to hold
		// the ONE root the node needs, and on a Mac that root is the system
		// launchd domain: only a daemon there can bootstrap/bootout the
		// harness, which is itself a system LaunchDaemon. A per-user agent
		// cannot reach the system domain and would leave the harness exactly
		// as unmanaged as no daemon at all.
		if runtime.GOOS == "darwin" {
			return installLaunchdDaemon(vars, opts.DryRun)
		}
		if !haveSystemd(true) {
			return fmt.Errorf("worker mode requires system systemd or darwin launchd")
		}
		return installSystemd(vars, opts)
	}

	switch {
	case runtime.GOOS == "darwin":
		return installLaunchd(vars, opts.DryRun)
	case haveSystemd(opts.System):
		return installSystemd(vars, opts)
	default:
		// No supervisor. Say so and hand over the one-liner, rather than
		// writing a unit into a directory nothing reads and reporting success.
		return fmt.Errorf(`no service manager detected (systemd is not running here).

This is normal on WSL2 without systemd. Two options:

  1. Enable systemd, then re-run this command:
       printf '[boot]\nsystemd=true\n' | sudo tee -a /etc/wsl.conf
       # then, from Windows:  wsl --shutdown   (and reopen the distro)

  2. Run it in the background as-is (no unit file, no root, survives logout):
       nohup %s run --root %s >> %s/.noo-host-spool/hostd.log 2>&1 &

The daemon behaves identically either way; systemd only adds restart-on-crash
and start-on-boot`, bin, root, root)
	}
}

func haveSystemd(system bool) bool {
	if _, err := exec.LookPath("systemctl"); err != nil {
		return false
	}
	args := []string{"is-system-running"}
	if !system {
		args = append([]string{"--user"}, args...)
	}
	// Ignore the exit code: `is-system-running` returns non-zero for
	// "degraded", which is extremely common on a developer box and does not
	// mean systemd is unusable. Only "offline"/failure-to-connect matters, and
	// those surface as an error running the command at all.
	out, err := exec.Command("systemctl", args...).CombinedOutput()
	if err != nil && len(bytes.TrimSpace(out)) == 0 {
		return false
	}
	s := string(bytes.TrimSpace(out))
	return s != "offline" && s != ""
}

func installSystemd(vars unitVars, opts InstallOptions) error {
	tmpl := systemdUnitTmpl
	if opts.Mode == ModeWorker {
		tmpl = workerUnitTmpl
	}
	body, err := render(tmpl, vars)
	if err != nil {
		return err
	}

	var unitPath string
	sysctl := func(args ...string) *exec.Cmd {
		return exec.Command("systemctl", append([]string{"--user"}, args...)...)
	}
	if opts.System {
		unitPath = "/etc/systemd/system/noo-hostd.service"
		sysctl = func(args ...string) *exec.Cmd { return exec.Command("systemctl", args...) }
	} else {
		home, _ := os.UserHomeDir()
		unitPath = filepath.Join(home, ".config", "systemd", "user", "noo-hostd.service")
	}

	if opts.DryRun {
		fmt.Printf("# would write %s\n\n%s", unitPath, body)
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(unitPath), 0o755); err != nil {
		return fmt.Errorf("cannot create %s (system installs need sudo): %w", filepath.Dir(unitPath), err)
	}
	if err := os.WriteFile(unitPath, []byte(body), 0o644); err != nil {
		return fmt.Errorf("cannot write %s (system installs need sudo): %w", unitPath, err)
	}
	fmt.Printf("wrote %s\n", unitPath)

	// `restart`, not `enable --now`: --now is a no-op on an ALREADY-ACTIVE
	// service, so re-running install after upgrading the binary left the old
	// process serving — observed live, where a re-run
	// "upgraded" the daemon and the very defect the upgrade fixed then fired
	// again from the old process. restart also starts a stopped service, so
	// the fresh-install path is unchanged. The daemon is idle between scan
	// ticks; a restart can at worst orphan one just-claimed .processing file,
	// which the claim-by-rename design already treats as evidence, not a lock.
	for _, args := range [][]string{{"daemon-reload"}, {"enable", "noo-hostd"}, {"restart", "noo-hostd"}} {
		c := sysctl(args...)
		c.Stdout, c.Stderr = os.Stdout, os.Stderr
		if err := c.Run(); err != nil {
			return fmt.Errorf("systemctl %v failed: %w", args, err)
		}
	}

	scope := "--user "
	if opts.System {
		scope = ""
	}
	fmt.Printf("noo-hostd is running. Logs: journalctl %s-u noo-hostd -f\n", scope)
	if !opts.System {
		// Without lingering, the user manager stops at logout and takes the
		// daemon with it — on a headless controller that means it is dead
		// between SSH sessions, which looks exactly like "the spool stopped
		// working for no reason".
		fmt.Printf("To keep it running when you are logged out: sudo loginctl enable-linger %s\n", os.Getenv("USER"))
	}
	return nil
}

func installLaunchd(vars unitVars, dryRun bool) error {
	body, err := render(launchdPlistTmpl, vars)
	if err != nil {
		return err
	}
	home, _ := os.UserHomeDir()
	plist := filepath.Join(home, "Library", "LaunchAgents", "net.personifai.noo-hostd.plist")
	if dryRun {
		fmt.Printf("# would write %s\n\n%s", plist, body)
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(plist), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(plist, []byte(body), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s\n", plist)
	_ = exec.Command("launchctl", "unload", plist).Run() // ignore: not loaded yet on first install
	c := exec.Command("launchctl", "load", "-w", plist)
	c.Stdout, c.Stderr = os.Stdout, os.Stderr
	if err := c.Run(); err != nil {
		return fmt.Errorf("launchctl load failed: %w", err)
	}
	fmt.Printf("noo-hostd is running. Logs: tail -f %s/.noo-host-spool/hostd.log\n", vars.Root)
	return nil
}

// WorkerDaemonLabel is the Darwin worker daemon's launchd label; its plist
// lives in the system domain because that is the only domain that can
// manage the harness LaunchDaemon. Shared with the applier and the
// dismantle path so nobody spells it twice.
const WorkerDaemonLabel = "net.noomesh.hostd"

// WorkerDaemonPlist is where installLaunchdDaemon writes.
const WorkerDaemonPlist = "/Library/LaunchDaemons/" + WorkerDaemonLabel + ".plist"

const workerLaunchdPlistTmpl = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <!-- noo-hostd, worker mode, Darwin.
       The ONLY root process a Mac worker runs for cluster reasons. No
       listener: the node agent (unprivileged) writes spool files into
       {{.Spool}}; this daemon performs the ops that need the system launchd
       domain — today the harness lifecycle — and nothing else.
       Generated by "noo-hostd install --mode worker"; do not hand-edit. -->
  <key>Label</key><string>net.noomesh.hostd</string>
  <key>ProgramArguments</key><array>
    <string>{{.Bin}}</string><string>run</string><string>--mode</string><string>worker</string>
  </array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>EnvironmentVariables</key><dict>
    <key>PATH</key><string>/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin</string>
  </dict>
  <key>StandardOutPath</key><string>/var/log/noo-hostd.log</string>
  <key>StandardErrorPath</key><string>/var/log/noo-hostd.log</string>
</dict></plist>
`

// installLaunchdDaemon writes the worker daemon into the system domain and
// bootstraps it. Must run as root, which is exactly the case: the Darwin
// applier (`noo node fetch`) runs as root under launchd.
func installLaunchdDaemon(vars unitVars, dryRun bool) error {
	body, err := render(workerLaunchdPlistTmpl, vars)
	if err != nil {
		return err
	}
	if dryRun {
		fmt.Printf("# would write %s\n\n%s", WorkerDaemonPlist, body)
		return nil
	}
	if os.Geteuid() != 0 {
		return fmt.Errorf("worker mode on darwin installs a system LaunchDaemon and must run as root")
	}
	if err := os.WriteFile(WorkerDaemonPlist, []byte(body), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s\n", WorkerDaemonPlist)
	// bootout first so a re-install picks up the new binary; "not loaded"
	// on a first install is not an error.
	_ = exec.Command("launchctl", "bootout", "system/"+WorkerDaemonLabel).Run()
	c := exec.Command("launchctl", "bootstrap", "system", WorkerDaemonPlist)
	c.Stdout, c.Stderr = os.Stdout, os.Stderr
	if err := c.Run(); err != nil {
		return fmt.Errorf("launchctl bootstrap failed: %w", err)
	}
	fmt.Printf("noo-hostd (worker) is running. Logs: tail -f /var/log/noo-hostd.log\n")
	return nil
}

// Uninstall stops and removes the service definition.
func Uninstall(system bool) error {
	if runtime.GOOS == "darwin" {
		// The worker daemon, if present, lives in the system domain.
		if _, err := os.Stat(WorkerDaemonPlist); err == nil {
			_ = exec.Command("launchctl", "bootout", "system/"+WorkerDaemonLabel).Run()
			return os.Remove(WorkerDaemonPlist)
		}
		home, _ := os.UserHomeDir()
		plist := filepath.Join(home, "Library", "LaunchAgents", "net.personifai.noo-hostd.plist")
		_ = exec.Command("launchctl", "unload", plist).Run()
		return os.Remove(plist)
	}
	args := []string{"disable", "--now", "noo-hostd"}
	unitPath := "/etc/systemd/system/noo-hostd.service"
	if !system {
		args = append([]string{"--user"}, args...)
		home, _ := os.UserHomeDir()
		unitPath = filepath.Join(home, ".config", "systemd", "user", "noo-hostd.service")
	}
	_ = exec.Command("systemctl", args...).Run()
	return os.Remove(unitPath)
}

func render(tmpl string, vars unitVars) (string, error) {
	t, err := template.New("unit").Parse(tmpl)
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, vars); err != nil {
		return "", err
	}
	return buf.String(), nil
}

// Status reports whether a live daemon is serving the given spool, for
// `noo-hostd status` and for anything else that needs to know before promising
// a repair.
func Status(ctx context.Context, spool string) (string, error) {
	hb, err := ReadHeartbeat(spool)
	if err != nil {
		if os.IsNotExist(err) {
			return "", fmt.Errorf("no heartbeat in %s — noo-hostd has never run against this spool", spool)
		}
		return "", err
	}
	if hb.Stale(nowUTC()) {
		return "", fmt.Errorf("heartbeat is STALE (last %s, interval %ds) — the daemon is not running; "+
			"commands written to this spool will never execute", hb.TS, hb.Interval)
	}
	return fmt.Sprintf("alive  pid=%d version=%s since=%s ops=%v", hb.PID, hb.Version, hb.StartedAt, hb.Ops), nil
}
