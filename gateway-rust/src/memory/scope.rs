//! Audience scoping for the gateway's own SQL reads of the knowledge base
//!
//!
//! `scope_allows` lets a User-tier token read every GET, so the listing and
//! graph routes that read `docs`, `entities` and `edges` directly were
//! answering with every person's titles, entity names and evidence snippets.
//! Retrieval never had the problem: `worker.rag.query` filters by the
//! caller's role set. This module gives the direct-SQL routes the same
//! audience.
//!
//! ## One resolver, not two
//!
//! The role set (`user:<account>`, `company`, `system`, granted `team:*`,
//! admin = unrestricted, `generated` opt-in) is decided in ONE place:
//! `src/noomesh/workers/kb.py::_resolve_kb_roles`. The gateway does not port
//! it. It asks the worker (`worker.rag.audience`, [`resolve`]) and applies
//! the answer as SQL. What lives here is only the *predicate* that turns a
//! role set into a row filter, and that is trellion's
//! `pageindex_store._ROLES_WHERE` restated once ([`DOC_VISIBLE`]).
//!
//! ## Provenance
//!
//! A document row carries `metadata.roles`. Everything derived from a
//! document inherits readability through a link the schema already has:
//!
//! * entity  -> `mentions.page_id` -> `pages.doc_id` -> `docs`. An entity is
//!   readable when at least ONE mention sits on a readable document.
//! * edge    -> both endpoints readable, AND, when `evidence_json.doc_id` is
//!   present (the graph builder always writes it), that document readable.
//!   The evidence also carries a verbatim snippet of the page, so an edge
//!   between two public entities cannot be shown when it was drawn from a
//!   private page.
//! * cluster -> shown when at least one member is readable, with its
//!   READABLE members only (`member_count` is the readable count). A cluster's
//!   stored name is generated by an LLM from ALL its members and may describe
//!   a private one, so a cluster with any unreadable member is labelled
//!   neutrally from its readable members ([`neutral_cluster_label`]: the top
//!   three by membership score, `+N more`), never with the stored name. A
//!   cluster whose members are all readable keeps its stored name. Per-audience
//!   reclustering is the real fix and is still open.
//!
//! Entities with no mention at all are unreadable to a restricted caller: no
//! provenance, no proof it is theirs.
//!
//! Every statement here takes the role set as `$1`; further parameters
//! follow. An unrestricted caller never reaches these statements: the
//! facade keeps the original unfiltered SQL for [`Audience::Unrestricted`].

