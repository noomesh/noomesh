/// What the operator's review filters narrow `GET /api/v1/docs` to
/// Every field is ANDed with the caller's audience
/// predicate, never OR'd: a filter can only remove rows, so a restricted
/// caller cannot widen their view by asking for `?audience=admin`.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct DocFilter {
    /// Documents with no audience tag at all (absent key, null, or `[]`).
    pub untagged: bool,
    /// Documents whose `metadata.roles` contains this tag. A trailing `*` is
    /// a prefix match: `user:*` is every personal tier.
    pub audience: Option<String>,
    /// `source_uri` glob, same dialect as `noo rag retag --match`.
    pub source_glob: Option<String>,
    /// Case-insensitive title substring.
    pub title: Option<String>,
}

/// Escape the LIKE metacharacters (Postgres' default escape is backslash).
fn like_escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('%', "\\%").replace('_', "\\_")
}

/// The glob `noo rag retag --match` takes, as a LIKE pattern: the same
/// translation `workers/rag.py::_rag_retag` applies, so the listing and the
/// retag select the same documents for the same string.
pub fn glob_to_like(glob: &str) -> String {
    like_escape(glob).replace('*', "%").replace('?', "_")
}

/// `metadata.roles` as an array, whatever a malformed row holds there
/// (`jsonb_array_elements_text` raises on a scalar and would fail the whole
/// listing for one bad row).
const ROLES_ARR: &str = "(CASE WHEN jsonb_typeof(d.metadata->'roles') = 'array' \
     THEN d.metadata->'roles' ELSE '[]'::jsonb END)";

/// The SELECT list of the listing: the six columns the listing always had,
/// then the ingest provenance block and the length of the audience history.
const DOC_COLS: &str = "d.doc_id::text, d.source_uri, d.title, d.hash, d.created_at, \
     d.metadata->'roles', d.metadata->'ingest', \
     (CASE WHEN jsonb_typeof(d.metadata->'audience_history') = 'array' \
           THEN jsonb_array_length(d.metadata->'audience_history') ELSE 0 END)::bigint";

/// `WHERE` for the listing. `$1` is the caller's role set, NULL for an
/// unrestricted caller; the filter binds follow from `$2` in the order
/// [`bind_filter`] binds them.
fn docs_where(f: &DocFilter, held: bool) -> String {
    let mut w = vec![format!("($1::text[] IS NULL OR {DOC_VISIBLE})"), not_held(held)];
    let mut n = 2;
    if f.untagged {
        w.push("(d.metadata->'roles' IS NULL OR d.metadata->'roles' IN ('null'::jsonb, '[]'::jsonb))".into());
    }
    if let Some(a) = &f.audience {
        if a.ends_with('*') {
            w.push(format!(
                "EXISTS (SELECT 1 FROM jsonb_array_elements_text({ROLES_ARR}) r WHERE r LIKE ${n})"
            ));
        } else {
            w.push(format!("jsonb_exists({ROLES_ARR}, ${n})"));
        }
        n += 1;
    }
    if f.source_glob.is_some() {
        w.push(format!("d.source_uri LIKE ${n}"));
        n += 1;
    }
    if f.title.is_some() {
        w.push(format!("d.title ILIKE ${n}"));
    }
    w.join(" AND ")
}

fn bind_filter<'q, O>(
    mut q: sqlx::query::QueryAs<'q, sqlx::Postgres, O, sqlx::postgres::PgArguments>,
    roles: Option<&'q [String]>,
    f: &'q DocFilter,
) -> sqlx::query::QueryAs<'q, sqlx::Postgres, O, sqlx::postgres::PgArguments> {
    q = q.bind(roles);
    if let Some(a) = &f.audience {
        q = match a.strip_suffix('*') {
            Some(prefix) => q.bind(format!("{}%", like_escape(prefix))),
            None => q.bind(a.clone()),
        };
    }
    if let Some(g) = &f.source_glob {
        q = q.bind(glob_to_like(g));
    }
    if let Some(t) = &f.title {
        q = q.bind(format!("%{}%", like_escape(t)));
    }
    q
}

/// `GET /api/v1/docs` rows the caller may read, newest first. `roles` None =
/// unrestricted.
pub async fn docs_list(
    db: &PgPool,
    roles: Option<&[String]>,
    f: &DocFilter,
    limit: i64,
    offset: i64,
) -> Result<Vec<DocRow>, sqlx::Error> {
    let sql = format!(
        "SELECT {DOC_COLS} FROM docs d WHERE {} \
         ORDER BY d.created_at DESC, d.doc_id LIMIT {limit} OFFSET {offset}",
        docs_where(f, crate::held_column::present(db).await)
    );
    bind_filter(sqlx::query_as::<_, DocRow>(sqlx::AssertSqlSafe(&*sql)), roles, f).fetch_all(db).await
}

/// `metadata.roles` of every readable document matching the filter, for the
/// audience summary. The filter applies here too: the summary describes the
/// same set the listing pages through.
pub async fn docs_roles_all(
    db: &PgPool,
    roles: Option<&[String]>,
    f: &DocFilter,
) -> Result<Vec<Option<Value>>, sqlx::Error> {
    let sql = format!("SELECT d.metadata->'roles' FROM docs d WHERE {}", docs_where(f, crate::held_column::present(db).await));
    let rows: Vec<(Option<Value>,)> = bind_filter(sqlx::query_as(sqlx::AssertSqlSafe(&*sql)), roles, f).fetch_all(db).await?;
    Ok(rows.into_iter().map(|r| r.0).collect())
}

/// One document for `GET /api/v1/docs/{doc_id}`: the row, its whole
/// metadata, how many pages it has and the opening text of the first few.
pub type DocDetailRow = (
    String,
    Option<String>,
    Option<String>,
    Option<String>,
    Option<chrono::DateTime<chrono::Utc>>,
    Option<Value>,
    i64,
    Option<String>,
);

/// The document, if the caller may read it. An unreadable document and one
/// that does not exist are the same answer (None), so the route cannot be
/// used to probe which ids exist.
pub async fn doc_detail(
    db: &PgPool,
    roles: Option<&[String]>,
    doc_id: &str,
) -> Result<Option<DocDetailRow>, sqlx::Error> {
    let sql = format!(
        "SELECT d.doc_id::text, d.source_uri, d.title, d.hash, d.created_at, d.metadata, \
                (SELECT COUNT(*) FROM pages p WHERE p.doc_id = d.doc_id), \
                (SELECT string_agg(t, E'\\n\\n' ORDER BY page_no) FROM ( \
                   SELECT page_no, left(text, 1000) AS t FROM pages \
                   WHERE doc_id = d.doc_id ORDER BY page_no LIMIT 3) x) \
         FROM docs d WHERE d.doc_id = $2::uuid AND ($1::text[] IS NULL OR {DOC_VISIBLE})"
    );
    sqlx::query_as::<_, DocDetailRow>(sqlx::AssertSqlSafe(&*sql))
        .bind(roles)
        .bind(doc_id)
        .fetch_optional(db)
        .await
}

