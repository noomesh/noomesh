/// The SQL of [`entity_pages`]; `held` as for [`scope_ctes`].
pub fn entity_pages_sql(held: bool) -> String {
    let nh = not_held(held);
    format!(
        "SELECT p.page_id::text, p.page_no, d.title \
         FROM pages p JOIN docs d ON d.doc_id = p.doc_id \
         WHERE {DOC_VISIBLE} AND {nh} \
           AND p.page_id IN (SELECT DISTINCT page_id FROM mentions WHERE entity_id = $2::uuid)"
    )
}

