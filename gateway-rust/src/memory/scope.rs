/// Who is asking, as the knowledge base sees it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Audience {
    /// Every tier (admin, `kb:unrestricted`, or a trusted internal caller
    /// that carries no user identity at all).
    Unrestricted,
    /// Only documents whose `metadata.roles` overlaps this set.
    Roles(Vec<String>),
}

impl Audience {
    pub fn roles(&self) -> Option<&[String]> {
        match self {
            Audience::Unrestricted => None,
            Audience::Roles(r) => Some(r),
        }
    }

    /// Parse the worker's `{"roles": null | [..]}` answer. Anything else is an
    /// error, never "unrestricted": a malformed reply must fail closed.
    pub fn from_worker(reply: &Value) -> Result<Self, String> {
        let payload = reply.get("data").unwrap_or(reply);
        if let Some(e) = payload.get("error").and_then(|e| e.as_str()) {
            return Err(e.to_string());
        }
        match payload.get("roles") {
            Some(Value::Null) => Ok(Audience::Unrestricted),
            Some(Value::Array(a)) => {
                let mut roles = Vec::with_capacity(a.len());
                for v in a {
                    match v.as_str() {
                        Some(s) => roles.push(s.to_string()),
                        None => return Err("audience roles must be strings".into()),
                    }
                }
                Ok(Audience::Roles(roles))
            }
            _ => Err("worker answered with no `roles` key".into()),
        }
    }
}

/// Ask the worker for the caller's audience.
///
/// `ctx` None is a machine caller (cluster HMAC, service key without a bound
/// user) that carries no user identity; those have always been unrestricted
/// on these routes and the HTTP rail still grants them full access. A user
/// caller is resolved by the worker from the SIGNED principal on the bus
/// message, so nothing in the body is trusted for it.
pub async fn resolve(
    state: &crate::state::AppState,
    ctx: &Option<axum::Extension<crate::auth::RequesterCtx>>,
) -> Result<Audience, crate::routes::AppError> {
    if ctx.is_none() {
        return Ok(Audience::Unrestricted);
    }
    // Empty body on purpose: the worker reads the caller from the signed
    // `Noo-Principal` header, never from anything the body says.
    let reply = state.memory().kb_audience(&serde_json::json!({})).await.map_err(|e| {
        if e.to_string().starts_with(crate::addons::DISABLED_MARKER) {
            crate::routes::AppError::Unavailable(crate::addons::DISABLED_MSG.to_string())
        } else {
            // Fail closed: a listing we cannot scope is not served.
            crate::routes::AppError::Unavailable(format!(
                "cannot resolve the caller's knowledge-base audience: {e}"
            ))
        }
    })?;
    Audience::from_worker(&reply).map_err(|e| {
        crate::routes::AppError::Unavailable(format!(
            "cannot resolve the caller's knowledge-base audience: {e}"
        ))
    })
}

/// The key a worker echoes on every reply it produced under a verified
/// restricted call (`workers/audience.py::AUDIENCE_KEY`).
pub const AUDIENCE_KEY: &str = "audience_filtered";

/// The reply, if it may be shown to `audience`; `None` = refuse.
///
/// The Intelligent-tier graph handlers and the curriculum run
/// in the worker over `trellion_intel`, which this stack does NOT version-pin
/// (the image is built from its `dev`). The gateway passes the audience down
/// as `roles`; an older worker, or a worker over an older intel, ignores or
/// rejects it and would answer for the whole corpus. So a restricted caller is
/// only ever given a reply that POSITIVELY says it was filtered
/// (`audience_filtered: true`, at the top or inside the `data` envelope).
/// Anything else (no key, `false`, a non-boolean, an error from a refusal)
/// is dropped: fail closed. The marker is internal and removed before the
/// reply is forwarded, so the public shape is the unrestricted one.
///
/// An unrestricted caller is never affected.
pub fn confirm_audience(audience: &Audience, mut reply: Value) -> Option<Value> {
    if matches!(audience, Audience::Unrestricted) {
        return Some(reply);
    }
    let confirmed = |v: &Value| v.get(AUDIENCE_KEY).and_then(Value::as_bool) == Some(true);
    let payload_confirmed = match reply.get("data") {
        Some(d) if d.is_object() => confirmed(d),
        _ => confirmed(&reply),
    };
    if !payload_confirmed {
        return None;
    }
    if let Some(d) = reply.get_mut("data").and_then(Value::as_object_mut) {
        d.remove(AUDIENCE_KEY);
    } else if let Some(o) = reply.as_object_mut() {
        o.remove(AUDIENCE_KEY);
    }
    Some(reply)
}

/// The refusal for a reply [`confirm_audience`] dropped: 503, because the
/// capability cannot be served audience-safely by what is deployed, not
/// because the caller did anything wrong. Names no data from the dropped reply.
pub fn unconfirmed_response(what: &str) -> (axum::http::StatusCode, axum::Json<Value>) {
    (
        axum::http::StatusCode::SERVICE_UNAVAILABLE,
        axum::Json(serde_json::json!({
            "error": "this capability could not confirm that its answer was filtered by your \
                      knowledge-base audience (the Intelligent-tier worker may be an older \
                      build than the gateway); it is refused rather than served unfiltered",
            "capability": what,
            "followup": 1306,
        })),
    )
}

/// The label of a cluster some of whose members the caller cannot read: the
/// top three READABLE member names (best first) plus `+N more`. Never the
/// stored label. The Intelligent tier's audience scope builds the
/// same string for `search-clusters`.
pub fn neutral_cluster_label(names: &[String], readable: i64) -> String {
    let top: Vec<&str> = names.iter().take(3).map(|s| s.as_str()).filter(|s| !s.is_empty()).collect();
    let mut label = top.join(", ");
    let extra = readable - top.len() as i64;
    if extra > 0 && !top.is_empty() {
        label.push_str(&format!(" +{extra} more"));
    }
    if label.is_empty() {
        "(cluster)".to_string()
    } else {
        label
    }
}

/// trellion `pageindex_store._ROLES_WHERE`, for a `docs` row aliased `d`,
/// with the role set in `$1`: tagged documents match by overlap; untagged
/// (legacy) ones only when the set carries the generic `user` tier, which a
/// restricted caller never has.
pub const DOC_VISIBLE: &str = "( (jsonb_exists(COALESCE(d.metadata, '{}'::jsonb), 'roles') \
       AND jsonb_exists_any(d.metadata->'roles', $1::text[])) \
     OR (NOT jsonb_exists(COALESCE(d.metadata, '{}'::jsonb), 'roles') \
       AND 'user' = ANY($1::text[])) )";

/// A held document (`docs.held_at`, trellion migration 105) is kept but out
/// of embedding and search. [`not_held`] is ANDed into every listing and
/// graph read built on [`DOC_VISIBLE`]; `held` is whether the column exists
/// yet ([`crate::held_column::present`]) and is `TRUE` when it does not.
fn not_held(held: bool) -> String {
    crate::held_column::not_held("d", held)
}


/// The three scoped views every graph read is built from. `$1` = role set.
fn scope_ctes(held: bool) -> String {
    let nh = not_held(held);
    format!(
        "WITH scoped_docs AS ( \
            SELECT d.doc_id FROM docs d WHERE {DOC_VISIBLE} AND {nh} ), \
         scoped_entities AS ( \
            SELECT e.* FROM entities e WHERE EXISTS ( \
              SELECT 1 FROM mentions m JOIN pages p ON p.page_id = m.page_id \
              WHERE m.entity_id = e.entity_id \
                AND p.doc_id IN (SELECT doc_id FROM scoped_docs)) ), \
         scoped_edges AS ( \
            SELECT ed.* FROM edges ed \
            WHERE ed.src_entity_id IN (SELECT entity_id FROM scoped_entities) \
              AND ed.dst_entity_id IN (SELECT entity_id FROM scoped_entities) \
              AND (ed.evidence_json->>'doc_id' IS NULL \
                   OR ed.evidence_json->>'doc_id' IN (SELECT doc_id::text FROM scoped_docs)) )"
    )
}

