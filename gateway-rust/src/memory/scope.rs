/// Top entities by degree, counting only readable edges between readable
/// entities, so a hidden edge cannot inflate (or reveal itself in) a number.
pub async fn top_entities(
    db: &PgPool,
    roles: &[String],
    min_degree: i32,
    entity_type: Option<&str>,
    limit: i32,
) -> Result<Vec<crate::repo::graph::EntityDegree>, sqlx::Error> {
    let sql = format!(
        "{}, degrees AS ( \
            SELECT entity_id, COUNT(*) AS deg FROM ( \
              SELECT src_entity_id AS entity_id FROM scoped_edges \
              UNION ALL SELECT dst_entity_id FROM scoped_edges) x GROUP BY entity_id ) \
         SELECT e.entity_id::text, e.canonical_name, e.type, d.deg \
         FROM scoped_entities e JOIN degrees d ON e.entity_id = d.entity_id \
         WHERE d.deg >= $2 AND ($3::text IS NULL OR e.type = $3) \
         ORDER BY d.deg DESC LIMIT $4",
        scope_ctes(crate::held_column::present(db).await)
    );
    sqlx::query_as(sqlx::AssertSqlSafe(&*sql))
        .bind(roles)
        .bind(i64::from(min_degree))
        .bind(entity_type)
        .bind(i64::from(limit))
        .fetch_all(db)
        .await
}

