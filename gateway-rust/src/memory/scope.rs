/// Clusters with at least one readable member (see the module docs): each is
/// returned with its READABLE member count, and, unless every member is
/// readable, a neutral label built from the readable members instead of the
/// stored one. `min_members` applies to the readable count: it is what the
/// caller sees.
pub async fn clusters(
    db: &PgPool,
    roles: &[String],
    level: i32,
    min_members: i32,
    limit: i32,
) -> Result<Vec<ClusterRow>, sqlx::Error> {
    let sql = format!(
        "{} SELECT c.cluster_id::text, c.name, c.level, c.member_count, cnt.total, cnt.readable, cnt.top \
         FROM entity_clusters c \
         CROSS JOIN LATERAL ( \
             SELECT COUNT(*) AS total, \
                    COUNT(se.entity_id) AS readable, \
                    COALESCE((array_agg(se.canonical_name \
                        ORDER BY m.membership_score DESC NULLS LAST, se.canonical_name) \
                        FILTER (WHERE se.entity_id IS NOT NULL))[1:3], ARRAY[]::text[]) AS top \
             FROM entity_cluster_members m \
             LEFT JOIN scoped_entities se ON se.entity_id = m.entity_id \
             WHERE m.cluster_id = c.cluster_id) cnt \
         WHERE c.level = $2 AND cnt.readable > 0 AND cnt.readable >= $3 \
         ORDER BY cnt.readable DESC, c.cluster_id LIMIT $4",
        scope_ctes(crate::held_column::present(db).await)
    );
    let rows: Vec<(String, String, i32, i32, i64, i64, Vec<String>)> = sqlx::query_as(sqlx::AssertSqlSafe(&*sql))
        .bind(roles)
        .bind(level)
        .bind(min_members)
        .bind(limit)
        .fetch_all(db)
        .await?;
    Ok(rows
        .into_iter()
        .map(|(id, name, level, stored_count, total, readable, top)| {
            if readable == total {
                (id, name, level, stored_count)
            } else {
                (id, neutral_cluster_label(&top, readable), level, readable as i32)
            }
        })
        .collect())
}

/// Inter-cluster edge weights over readable edges only.
pub async fn cluster_edges(
    db: &PgPool,
    roles: &[String],
    level: i32,
    cluster_ids: &[String],
) -> Result<Vec<ClusterEdgeRow>, sqlx::Error> {
    let sql = format!(
        "{} SELECT m1.cluster_id::text AS src_cluster, m2.cluster_id::text AS dst_cluster, \
                COUNT(*) AS weight \
         FROM scoped_edges e \
         JOIN entity_cluster_members m1 ON m1.entity_id = e.src_entity_id \
         JOIN entity_cluster_members m2 ON m2.entity_id = e.dst_entity_id \
         JOIN entity_clusters c1 ON c1.cluster_id = m1.cluster_id AND c1.level = $2 \
         JOIN entity_clusters c2 ON c2.cluster_id = m2.cluster_id AND c2.level = $2 \
         WHERE m1.cluster_id::text = ANY($3::text[]) AND m2.cluster_id::text = ANY($3::text[]) \
           AND m1.cluster_id <> m2.cluster_id \
         GROUP BY m1.cluster_id, m2.cluster_id HAVING COUNT(*) >= 2 \
         ORDER BY weight DESC LIMIT 2000",
        scope_ctes(crate::held_column::present(db).await)
    );
    sqlx::query_as::<_, ClusterEdgeRow>(sqlx::AssertSqlSafe(&*sql))
        .bind(roles)
        .bind(level)
        .bind(cluster_ids)
        .fetch_all(db)
        .await
}

