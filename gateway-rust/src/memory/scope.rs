    #[tokio::test]
    async fn kb_docs_review_filters_apply_to_listing_and_summary_and_never_widen() {
        let Some(w) = world().await else {
            eprintln!("SKIPPED: set NOO_KB_AUDIENCE_TEST_DSN to run the DB-backed audience tests");
            return;
        };
        let db = &w.db;
        let long = "x".repeat(600);
        let x1 = add_doc(db, "Budget 100%_Draft", "gdrive://x1",
            json!({"roles": ["user:a", "team:x"],
                   "ingest": {"by": "a", "via": "cli", "at": "2026-10-01T00:00:00+00:00"},
                   "audience_history": [{"at": "t1", "by": "root", "from": ["admin"], "to": ["user:a"]},
                                        {"at": "t2", "by": "root", "from": ["user:a"], "to": ["user:a", "team:x"]}]}),
            &[&format!("P1{long}"), &format!("P2{long}"), &format!("P3{long}"), "P4-never-previewed"]).await;
        let _x2 = add_doc(db, "budget plan", "file:///notes/x2.md", json!({"roles": ["admin"]}), &[]).await;
        let _x3 = add_doc(db, "Unlabelled", "gdrive://x3", json!({"roles": []}), &[]).await;
        let _x4 = add_doc(db, "NullRoles", "gdrive://x4", json!({"roles": null}), &[]).await;
        let _x5 = add_doc(db, "Malformed", "file:///x5", json!({"roles": "oops"}), &[]).await;

        let admin = |filt: DocFilter| async move {
            docs_list(db, None, &filt, 100, 0).await.unwrap()
        };
        let set = |v: &[&str]| -> BTreeSet<String> { v.iter().map(|s| s.to_string()).collect() };

        // untagged: absent key, JSON null and [] — not a malformed scalar, not a tagged one.
        assert_eq!(keys(&admin(f(true, None, None, None)).await), set(&["legacy", "Unlabelled", "NullRoles"]));
        // audience: exact, and `user:*` = any personal tier.
        assert_eq!(keys(&admin(f(false, Some("company"), None, None)).await), set(&["co"]));
        assert_eq!(keys(&admin(f(false, Some("team:x"), None, None)).await), set(&["team_x", "Budget 100%_Draft"]));
        assert_eq!(keys(&admin(f(false, Some("user:*"), None, None)).await),
                   set(&["a_priv", "b_priv", "Budget 100%_Draft"]));
        assert_eq!(keys(&admin(f(false, Some("user:a"), None, None)).await), set(&["a_priv", "Budget 100%_Draft"]));
        // a malformed scalar `roles` must not fail the listing
        assert!(keys(&admin(f(false, Some("user:*"), None, None)).await).contains("a_priv"));
        // match: glob, with LIKE metacharacters in the glob taken literally.
        assert_eq!(keys(&admin(f(false, None, Some("gdrive://*"), None)).await),
                   set(&["Budget 100%_Draft", "Unlabelled", "NullRoles"]));
        assert_eq!(keys(&admin(f(false, None, Some("file:///notes/*"), None)).await), set(&["budget plan"]));
        assert!(admin(f(false, None, Some("file:///notes/x_.md"), None)).await.is_empty(), "`_` is literal in a glob");
        assert_eq!(keys(&admin(f(false, None, Some("file:///notes/x?.md"), None)).await), set(&["budget plan"]));
        // q: case-insensitive substring, `%` literal.
        assert_eq!(keys(&admin(f(false, None, None, Some("BUDGET"))).await), set(&["Budget 100%_Draft", "budget plan"]));
        assert_eq!(keys(&admin(f(false, None, None, Some("100%"))).await), set(&["Budget 100%_Draft"]));
        assert!(admin(f(false, None, None, Some("%zzz"))).await.is_empty());
        // filters AND together
        assert_eq!(keys(&admin(f(false, Some("user:*"), None, Some("budget"))).await), set(&["Budget 100%_Draft"]));
        assert!(admin(f(true, Some("company"), None, None)).await.is_empty());

        // Provenance and history length ride on each row.
        let rows = admin(f(false, None, Some("gdrive://x1"), None)).await;
        assert_eq!(rows.len(), 1);
        assert_eq!(rows[0].6.as_ref().unwrap()["via"], "cli");
        assert_eq!(rows[0].7, 2);
        let plain = admin(f(false, Some("company"), None, None)).await;
        assert!(plain[0].6.is_none());
        assert_eq!(plain[0].7, 0);

        // The summary covers the same filtered set as the listing.
        for filt in [f(true, None, None, None), f(false, Some("user:*"), None, None),
                     f(false, None, Some("gdrive://*"), None), f(false, None, None, Some("budget"))] {
            let n = admin(filt.clone()).await.len();
            assert_eq!(docs_roles_all(db, None, &filt).await.unwrap().len(), n, "summary for {filt:?}");
        }
        // Paging stays exact under a filter.
        let filt = f(false, Some("user:*"), None, None);
        let mut paged = BTreeSet::new();
        let mut off = 0;
        loop {
            let page = docs_list(db, None, &filt, 1, off).await.unwrap();
            if page.is_empty() { break; }
            paged.extend(keys(&page));
            off += 1;
        }
        assert_eq!(paged, set(&["a_priv", "b_priv", "Budget 100%_Draft"]));

        // ── a restricted caller: filters only ever remove rows ──────────
        let fx: Value = serde_json::from_str(FIXTURE).unwrap();
        let a = roles_of_caller(&fx, "a").unwrap();
        let restricted = |filt: DocFilter| {
            let a = a.clone();
            async move { docs_list(db, Some(&a), &filt, 100, 0).await.unwrap() }
        };
        let base = keys(&restricted(DocFilter::default()).await);
        assert_eq!(base, set(&["a_priv", "co", "sys", "Budget 100%_Draft"]));
        assert!(restricted(f(true, None, None, None)).await.is_empty(), "untagged is invisible to A");
        assert!(restricted(f(false, Some("admin"), None, None)).await.is_empty(), "?audience=admin does not reveal admin docs");
        assert!(restricted(f(false, Some("user:b"), None, None)).await.is_empty());
        assert_eq!(keys(&restricted(f(false, Some("user:*"), None, None)).await), set(&["a_priv", "Budget 100%_Draft"]),
                   "user:* is every personal tier A can READ, not every personal tier");
        assert_eq!(keys(&restricted(f(false, None, Some("file:///*"), None)).await), set(&["a_priv", "co", "sys"]));
        assert!(restricted(f(false, None, None, Some("budget"))).await.iter().all(|r| base.contains(r.2.as_ref().unwrap().trim_start_matches("title-"))));
        // Every filter result is a subset of what A could read unfiltered.
        for filt in [f(false, Some("*"), None, None), f(false, None, Some("*"), None), f(false, None, None, Some(""))] {
            assert!(keys(&restricted(filt).await).is_subset(&base));
        }
        assert_eq!(docs_roles_all(db, Some(&a), &f(false, Some("user:*"), None, None)).await.unwrap().len(), 2);

        // ── detail ──────────────────────────────────────────────────────
        let b_doc = w.doc["b_priv"].clone();
        let admin_view = doc_detail(db, None, &x1).await.unwrap().expect("admin reads x1");
        assert_eq!(admin_view.6, 4, "page count");
        let preview = admin_view.7.clone().unwrap();
        assert!(preview.starts_with("P1") && preview.contains("P3") && !preview.contains("P4-never"), "first three pages");
        assert_eq!(admin_view.5.as_ref().unwrap()["audience_history"].as_array().unwrap().len(), 2);
        assert!(doc_detail(db, None, &b_doc).await.unwrap().is_some());
        assert!(doc_detail(db, Some(&a), &b_doc).await.unwrap().is_none(), "A cannot read B's document by id");
        assert!(doc_detail(db, Some(&a), &w.doc["adm"]).await.unwrap().is_none());
        assert!(doc_detail(db, Some(&a), &w.doc["legacy"]).await.unwrap().is_none(), "untagged is unreadable to A");
        assert!(doc_detail(db, Some(&a), &x1).await.unwrap().is_some(), "x1 carries user:a");
        assert!(doc_detail(db, Some(&a), &uid()).await.unwrap().is_none(), "missing = unreadable");
        drop_world(w).await;
    }
