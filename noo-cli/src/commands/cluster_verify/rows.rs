//! The registry of verify rows: every row `noo cluster verify` (and `noo
//! security at-rest preflight-firmware`) can print. One entry per row:
//!
//! - `id`: the stable code programs branch on, written by hand, snake_case,
//!   never derived from `name` (a wording fix to `name` must not break a
//!   program). `noo --json cluster verify` prints it beside `name`.
//! - `name`: the display text (what the table shows).
//! - `scope`: where the row is judged and printed (`nodes[].checks`,
//!   `controller.checks`, a seat, or the firmware preflight).
//! - `verdicts`: the non-OK verdicts it can emit; `Check::checked` refuses,
//!   in a test build, a verdict not listed here.
//! - `meaning`, `clears`: one line each, for a person and an agent alike.
//! - `findings`: the finer codes, only where one row has several reasons.
//! - `shown_as`: the row the default table prints it inside, if it folds.
//! - `doc`: where the long explanation lives, if anywhere.
//!
//! docs/reference/verify-rows.md is generated from this file
//! (scripts/gen-verify-rows.py, checked by docs-check), which also checks
//! that every row the source builds is here and every row here is built.
//! Keep each entry in this exact shape: the generator parses it.

use super::Verdict;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Scope {
    Node,
    Controller,
    Seat,
    Preflight,
}

#[derive(Debug)]
#[allow(dead_code)] // read by the generator and the test guard
pub(crate) struct Finding {
    pub code: &'static str,
    pub clears: &'static str,
    pub needs_human: bool,
}

#[derive(Debug)]
#[allow(dead_code)] // read by the generator and the test guard
