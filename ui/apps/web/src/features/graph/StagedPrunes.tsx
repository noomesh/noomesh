import { toast } from 'sonner';
import { useAuth } from '@metis/core';
import { relTime } from '@/lib/format';
import { StatTiles } from '@/components/StatTiles';
import { StatusBadge } from '@/components/StatusBadge';
import { Button } from '@/components/ui/button';
import { useConfirm } from '@/components/ConfirmDialog';
import {
  useStagedPrunes,
  useRestorePrune,
  daysLeft,
  parsePgTime,
  RETENTION_DAYS,
  STAGED_LIMIT,
  type StagedPrune,
} from './usePrunes';

const isoOf = (s: string) => {
  const t = parsePgTime(s);
  return t == null ? null : new Date(t).toISOString();
};

function leftLabel(n: number | null): string {
  if (n == null) return 'window unknown';
  if (n === 0) return 'due for purge';
  return `${n}d left`;
}

/**
 * Graph → Staged prunes. Lists what graph_prune soft-deleted and restores a
 * row on request. Reading is open to any signed-in user (the list route is
 * read tier); restore is a write, so the button is disabled below operator
 * — the gateway would 403 it anyway.
 */
export function StagedPrunes() {
  const staged = useStagedPrunes();
  const restore = useRestorePrune();
  const confirm = useConfirm();
  const { isOperator } = useAuth();
  const restoringId = restore.isPending ? restore.variables?.stagingId : undefined;

  async function onRestore(row: StagedPrune) {
    const what = row.kind === 'edge' ? 'edge' : `entity "${row.label}"`;
    const ok = await confirm({
      title: `Restore ${row.kind === 'edge' ? 'this edge' : row.label}?`,
      description:
        row.kind === 'edge'
          ? `Puts ${row.label} back in the graph. It is skipped if either endpoint no longer exists.`
          : `Re-inserts the ${row.detail || 'entity'} with its ${row.edgeCount ?? 0} edges and ` +
            `${row.mentionCount ?? 0} mentions. If the same name and type was re-extracted since, the ` +
            `snapshot is grafted onto it. Embeddings are regenerated by the next reindex.`,
      confirmText: 'Restore',
    });
    if (!ok) return;
    restore.mutate(row, {
      onSuccess: (r) => {
        if (r.status === 'already_restored') {
          toast.info('Already restored', { description: row.label });
          return;
        }
        const bits: string[] = [];
        if (r.grafted) bits.push('grafted onto the existing entity');
        if (row.kind === 'entity') {
          bits.push(`${r.edgesRestored} edges back`);
          if (r.edgesSkipped) bits.push(`${r.edgesSkipped} skipped (endpoint gone)`);
        }
        toast.success(`Restored ${what}`, { description: bits.join(' · ') || row.label });
      },
      onError: (e) => toast.error('Restore failed', { description: (e as Error).message }),
    });
  }

  if (staged.isLoading) return <div className="state">Loading staged prunes…</div>;
  if (staged.isError) {
    return <div className="state err">{(staged.error as Error)?.message}</div>;
  }
  const d = staged.data;
  if (!d) return null;

  if (d.rows.length === 0) {
    return (
      <div className="state" data-testid="prunes-empty">
        Nothing is staged. The graph_prune task runs as a dry run unless its <code>dry_run</code>{' '}
        setting is turned off, so it only reports what it would prune.
        {d.note && <div className="prune-note">{d.note}</div>}
      </div>
    );
  }

  const soonest = d.rows.reduce<number | null>((min, r) => {
    const n = daysLeft(r.purgeAt);
    return n == null ? min : min == null ? n : Math.min(min, n);
  }, null);
  const shownEntities = d.rows.filter((r) => r.kind === 'entity').length;
  const shownEdges = d.rows.length - shownEntities;
  const truncated = shownEntities < d.entityTotal || shownEdges < d.edgeTotal;

  return (
    <>
      <StatTiles
        tiles={[
          { label: 'Staged entities', value: d.entityTotal.toLocaleString() },
          { label: 'Staged edges', value: d.edgeTotal.toLocaleString() },
          { label: 'Soonest purge', value: leftLabel(soonest), hot: soonest != null && soonest <= 3 },
        ]}
      />

      <p className="prune-help">
        Staged rows are kept {RETENTION_DAYS} days (the task's <code>staging_retention_days</code>{' '}
        default), then deleted for good by the next prune run that is not a dry run.
        {!isOperator && ' Restoring needs the operator role.'}
      </p>

      {d.rows.map((r) => {
        const busy = restoringId === r.stagingId;
        const left = daysLeft(r.purgeAt);
        const iso = isoOf(r.stagedAt);
        return (
          <div className="approval-row" key={`${r.kind}:${r.stagingId}`}>
            <div className="approval-main">
              <div className="approval-line1">
                <StatusBadge tone="neutral">{r.kind}</StatusBadge>
                {r.reason && <StatusBadge tone="warn">{r.reason}</StatusBadge>}
                <span className="approval-tool">{r.label}</span>
              </div>
              <div className="approval-meta">
                {r.kind === 'entity'
                  ? `${r.detail || 'entity'} · ${r.edgeCount} edges · ${r.mentionCount} mentions`
                  : `confidence ${r.confidence == null ? '—' : r.confidence.toFixed(2)}`}
                {' · '}
                <span title={iso ?? r.stagedAt}>staged {iso ? `${relTime(iso)} ago` : r.stagedAt || '—'}</span>
                {r.runId ? ` · run ${r.runId}` : ''}
                {' · '}
                <span
                  className={left != null && left <= 3 ? 'prune-left hot' : 'prune-left'}
                  title={r.purgeAt ? `Purge-eligible from ${new Date(r.purgeAt).toISOString()}` : undefined}
                >
                  {leftLabel(left)}
                </span>
              </div>
            </div>
            <div className="approval-actions">
              <Button
                size="sm"
                variant="outline"
                disabled={!isOperator || busy}
                onClick={() => onRestore(r)}
                title={isOperator ? `Put this ${r.kind} back in the graph.` : 'Restoring needs the operator role.'}
              >
                {busy ? 'Restoring…' : 'Restore'}
              </Button>
            </div>
          </div>
        );
      })}

      {truncated && (
        <div className="state">
          showing the newest {STAGED_LIMIT} of each kind — restore or wait out the window to see older rows
        </div>
      )}
    </>
  );
}
